		<h2 class="mt-4">Início da Aula</h2>

		<p>No Karate Kenshydokan, seguimos normas rígidas em relação ao pré-aula, que ocorre quando os alunos chegam ao dojo. Aqui estão as etapas importantes:</p>

		<ol>
			<li>Cumprimente seu companheiro e o mestre: Ao entrar no dojo, cumprimente seu companheiro de treino e o mestre, erguendo os braços no formato de um "X" e dizendo "oss" ou "osu".</li>
			<li>Prepare-se para o treino: Beba água, vá ao banheiro e vista seu KarateGi (Kimono).</li>
			<li>Autorização para subir no tatame: Peça permissão para subir no tatame, cumprimente o tatame e aguarde o início da aula em silêncio.</li>
		</ol>

		<p>Quando a aula começar, o mestre conduzirá um ritual de cumprimento, que inclui os seguintes passos:</p>

		<ul>
			<li>Mokuso: Meditação.</li>
			<li>Mokuso Yame: Pare de meditar.</li>
			<li>Shomen Ni Rei: Cumprimente a Essência do Karate.</li>
			<li>Otagai Ni Rei: Cumprimente seus parceiros de treino.</li>
			<li>Shihan Ni Rei: Cumprimente o Grão Mestre.</li>
			<li>Sensei Ni Rei: Cumprimente o Mestre.</li>
			<li>Kiritsu: Levante-se.</li>
		</ul>

		<p>Antes de iniciar o treino, haverá um aquecimento e alongamento coordenados pelo Sensei ou Sempai, seguidos de uma pausa para necessidades básicas. Não se esqueça de cumprimentar o tatame ao sair e ao voltar.</p>

		<p>O treino da aula pode incluir diferentes tipos de atividades, como Kihon, Yakusoku Kumite, Shiai Kumite, Jyu Kumite e Kata. Familiarize-se com essas nomenclaturas, pois são fundamentais para o seu progresso no karate.</p>

		<p>Lembre-se de que a jornada no karate exige dedicação e prática constante. Continue treinando com determinação e foco, pois o karate é uma busca pelo crescimento pessoal e aprimoramento constante. Oss!</p>
